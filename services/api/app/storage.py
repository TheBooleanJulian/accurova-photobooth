"""Object storage for photographs, behind one small interface.

Keys are always generated by the server (never taken from a request), and
objects are private: visitors reach them only through a download token.
"""

from pathlib import Path
from typing import Any, Protocol

from .config import Settings


class ObjectNotFound(KeyError):
    pass


class ObjectStorage(Protocol):
    name: str

    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...
    def status(self) -> str:
        """'local', 'connected' or 'error' for the health endpoint."""
        ...


class LocalStorage:
    """Filesystem storage for development and single-machine deployments."""

    name = "local"

    def __init__(self, root: Path):
        self.root = root.resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError("storage key escapes the storage root")
        return path

    def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_bytes(data)
        tmp.replace(path)  # atomic: readers never see a half-written file

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as e:
            raise ObjectNotFound(key) from e

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def status(self) -> str:
        return "local"


class R2Storage:
    """Cloudflare R2 through its S3-compatible API."""

    name = "r2"

    def __init__(self, bucket: str, client: Any):
        self.bucket = bucket
        self.client = client

    @classmethod
    def from_settings(cls, settings: Settings) -> "R2Storage":
        missing = [
            name
            for name in ("r2_account_id", "r2_access_key_id", "r2_secret_access_key", "r2_bucket")
            if not getattr(settings, name)
        ]
        if missing:
            raise RuntimeError(f"R2 storage selected but not configured: missing {', '.join(missing)}")
        import boto3  # imported lazily so local development needs no AWS SDK state

        client = boto3.client(
            "s3",
            endpoint_url=f"https://{settings.r2_account_id}.r2.cloudflarestorage.com",
            aws_access_key_id=settings.r2_access_key_id,
            aws_secret_access_key=settings.r2_secret_access_key,
            region_name="auto",
        )
        return cls(settings.r2_bucket, client)

    @staticmethod
    def _is_missing(error: Exception) -> bool:
        code = getattr(error, "response", {}).get("Error", {}).get("Code", "")
        return str(code) in {"NoSuchKey", "404", "NotFound"}

    def put(self, key: str, data: bytes, content_type: str) -> None:
        self.client.put_object(Bucket=self.bucket, Key=key, Body=data, ContentType=content_type)

    def get(self, key: str) -> bytes:
        try:
            return self.client.get_object(Bucket=self.bucket, Key=key)["Body"].read()
        except Exception as e:
            if self._is_missing(e):
                raise ObjectNotFound(key) from e
            raise

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=key)

    def status(self) -> str:
        try:
            self.client.head_bucket(Bucket=self.bucket)
            return "connected"
        except Exception:
            return "error"


def build_storage(settings: Settings) -> ObjectStorage:
    if settings.storage_backend == "r2":
        return R2Storage.from_settings(settings)
    return LocalStorage(settings.storage_dir)
